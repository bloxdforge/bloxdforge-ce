export function getBloxdTextureName(mcId: string): string {
    const cleanId = mcId.replace('minecraft:', '').split('[')[0];
    const namespacedId = `minecraft:${cleanId}`;
    if (TEXTURE_MAP[namespacedId]) {
        return TEXTURE_MAP[namespacedId];
    }
    if (cleanId.endsWith('_concrete_powder')) {
        const color = cleanId.replace('_concrete_powder', '');
        return `chalk_${color}.png`;
    }
    const baseBlockId = namespacedId.replace('_stairs', '').replace('_slab', '');
    if (TEXTURE_MAP[baseBlockId]) {
        return TEXTURE_MAP[baseBlockId];
    }
    return "stone.png";
}
